import assert from 'node:assert/strict';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { test } from 'node:test';

import { getBounds } from '@gltf-transform/core';
import sharp from 'sharp';

import { loadFusionObj, materialFinish, partFrame, uvsForTriangle, woodSpeciesFromName } from './fusion-obj.mjs';
import { optimizeDocument } from './optimize.mjs';

test('material names pick walnut or maple', () => {
  assert.equal(woodSpeciesFromName('3D_Walnut_-_Semigloss'), 'walnut');
  assert.equal(woodSpeciesFromName('3D_Maple_-_Semigloss'), 'maple');
  assert.equal(woodSpeciesFromName('Steel'), null);
});

test('leather names and flat gray or black become matte leather', () => {
  assert.equal(materialFinish('Leather_-_Matte_(Black)', [0, 0, 0]), 'leather');
  assert.equal(materialFinish('Opaque(63,63,63)', [0.25098, 0.25098, 0.25098]), 'leather');
  assert.equal(materialFinish('Opaque(86,58,26)', [0.337255, 0.227451, 0.101961]), 'walnut');
  assert.equal(materialFinish('3D_Walnut_-_Semigloss', [0.337255, 0.227451, 0.101961]), 'walnut');
});

test('turned legs are lathed and the seat is a box', () => {
  const leg = partFrame([-2.8, -3.1, 0], [2.8, 3.2, 46]);
  assert.equal(leg.mode, 'lathe');
  assert.equal(leg.grain, 2);
  const post = partFrame([-2.7, -6, 0], [2.7, 5.9, 94]);
  assert.equal(post.mode, 'box');
  assert.equal(post.grain, 2);
  const seat = partFrame([-24, -22, 40], [24, 22, 45]);
  assert.equal(seat.mode, 'box');
  assert.equal(seat.grain, 1);
});

test('a lathe triangle that crosses the seam does not span the whole wrap', () => {
  const frame = partFrame([-3, -3, 0], [3, 3, 40]);
  const points = [
    [-3, 0.05, 10],
    [-3, -0.05, 10],
    [-2.9, 0, 12],
  ];
  const uvs = uvsForTriangle(points, [-1, 0, 0], frame);
  const us = uvs.map((uv) => uv[0]);
  const span = Math.max(...us) - Math.min(...us);
  assert.ok(span < 0.5, `seam span ${span}`);
});

test('a Fusion OBJ in centimeters and Z-up becomes a meter-tall Y-up chair', async () => {
  const directory = await mkdtemp(path.join(tmpdir(), 'fusion-obj-'));
  const obj = path.join(directory, 'Tiny.obj');
  await writeFile(path.join(directory, 'Tiny.mtl'), 'newmtl 3D_Walnut_-_Semigloss\nKd 0.34 0.23 0.10\n');
  await writeFile(obj, [
    '# WaveFront *.obj file (generated by Autodesk ATF)',
    'mtllib Tiny.mtl',
    'g Post',
    'v -2 -2 0',
    'v 2 -2 0',
    'v 0 2 95',
    'vn 0 0 1',
    'usemtl 3D_Walnut_-_Semigloss',
    'f 1//1 2//1 3//1',
    '',
  ].join('\n'));

  const loaded = await loadFusionObj(obj, { textureSize: 32 });
  assert.equal(loaded.summaries[0].species, 'walnut');
  assert.equal(loaded.summaries[0].flatColor, true);
  const report = await optimizeDocument(loaded.document, { units: 'auto', up: 'z', compress: 'none' });
  const bounds = getBounds(loaded.document.getRoot().getDefaultScene());
  const height = bounds.max[1] - bounds.min[1];
  assert.equal(report.units, 'cm');
  assert.ok(Math.abs(height - 0.95) < 1e-3, `height ${height}`);
  assert.ok(Math.abs(bounds.min[1]) < 1e-4);
  const color = loaded.document.getRoot().listTextures().find((texture) => texture.getName() === 'walnut-color');
  assert.ok(color);
  const meta = await sharp(Buffer.from(color.getImage())).metadata();
  assert.equal(meta.format, 'webp');
});

test('a gray Fusion material stays leather when wood is forced to walnut', async () => {
  const directory = await mkdtemp(path.join(tmpdir(), 'fusion-leather-'));
  const obj = path.join(directory, 'Seat.obj');
  await writeFile(path.join(directory, 'Seat.mtl'), [
    'newmtl Opaque(86,58,26)',
    'Kd 0.337255 0.227451 0.101961',
    'newmtl Opaque(63,63,63)',
    'Kd 0.250980 0.250980 0.250980',
    '',
  ].join('\n'));
  await writeFile(obj, [
    'mtllib Seat.mtl',
    'g Frame',
    'v 0 0 0',
    'v 10 0 0',
    'v 0 10 40',
    'usemtl Opaque(86,58,26)',
    'f 1 2 3',
    'g Seat',
    'v 0 0 42',
    'v 20 0 42',
    'v 0 20 48',
    'usemtl Opaque(63,63,63)',
    'f 4 5 6',
    '',
  ].join('\n'));
  const loaded = await loadFusionObj(obj, { wood: 'walnut', textureSize: 16 });
  const byName = Object.fromEntries(loaded.summaries.map((item) => [item.material, item.species]));
  assert.equal(byName['Opaque(86,58,26)'], 'walnut');
  assert.equal(byName['Opaque(63,63,63)'], 'leather');
  assert.ok(loaded.document.getRoot().listTextures().some((texture) => texture.getName() === 'leather-color'));
});
